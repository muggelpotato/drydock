# Fabulously Optimized + drydock.toml + modpack/overrides/
# --update updates addon mods to their latest versions, unless pinned in drydock.toml
import json
import shutil
import subprocess
import sys
import tempfile
import tomllib
import urllib.parse
import urllib.request
from pathlib import Path

HERE = Path(__file__).parent
ROOT = HERE.parent
OVERRIDES = HERE / "overrides"
LOCK = HERE / "drydock.lock"
TEMP = tempfile.TemporaryDirectory(ignore_cleanup_errors=True)  # packwiz
PACK = Path(TEMP.name)
config = tomllib.loads((ROOT / "drydock.toml").read_text("utf-8"))
minecraft, cfg = config["minecraft"], config["modpack"]
OUT = ROOT / "build" / f"{cfg['name']}-{cfg['version']}.mrpack"
lock = tomllib.loads(LOCK.read_text("utf-8")) if LOCK.exists() and "--update" not in sys.argv else {}
if lock.get("minecraft") != minecraft:
    lock = {}
pins = lock.get("mods", {})
failed = []


def get(url):
    return urllib.request.urlopen(url, timeout=60).read()

def packwiz(*args, check=True):
    return subprocess.run(["packwiz", "-y", *args], cwd=PACK, check=check).returncode

def add(slug):
    url = f"https://modrinth.com/mod/{slug}" + (f"/version/{pins[slug]}" if slug in pins else "")
    if packwiz("modrinth", "add", url, check=False):
        failed.append(slug)

def merge(base, patch):
    for key, value in patch.items():
        if isinstance(value, dict) and isinstance(base.get(key), dict):
            merge(base[key], value)
        else:
            base[key] = value
    return base


fo_commit = lock.get("fo") or json.loads(get("https://api.github.com/repos/Fabulously-Optimized/fabulously-optimized/git/ref/heads/main"))["object"]["sha"]
fo_url = f"https://raw.githubusercontent.com/Fabulously-Optimized/fabulously-optimized/{fo_commit}/Packwiz/{minecraft}/"

packwiz("init", "--name", cfg["name"], "--version", cfg["version"], "--mc-version", minecraft, "--modloader", "fabric", *(["--fabric-version", lock["fabric"]] if lock else ["--fabric-latest"]))

squash = lambda text: text.lower().translate(str.maketrans("", "", " -_"))
fo_files = [file["file"] for file in tomllib.loads(get(fo_url + "index.toml").decode())["files"]]
fo_mods = {path: get(fo_url + urllib.parse.quote(path)) for path in fo_files if path.endswith(".pw.toml")}
labels = {path: squash(path + "/" + tomllib.loads(fo_mods[path].decode())["name"] if path in fo_mods else path) for path in fo_files}
unmatched = [word for word in cfg["exclude"] if not any(squash(word) in label for label in labels.values())]
for path in fo_files:
    if not any(squash(word) in labels[path] for word in cfg["exclude"]):
        (PACK / path).parent.mkdir(parents=True, exist_ok=True)
        (PACK / path).write_bytes(fo_mods.get(path) or get(fo_url + urllib.parse.quote(path)))

for src in OVERRIDES.rglob("*"):
    if not src.is_file():
        continue
    dst = PACK / src.relative_to(OVERRIDES)
    dst.parent.mkdir(parents=True, exist_ok=True)
    if dst.exists() and src.name == "options.txt":
        lines = (dst.read_bytes() + b"\n" + src.read_bytes()).decode().splitlines()
        options = dict(line.split(":", 1) for line in lines if ":" in line)
        dst.write_bytes("\n".join(f"{k}:{v}" for k, v in options.items()).encode())
    elif dst.exists() and src.suffix == ".json":
        merged = merge(json.loads(dst.read_bytes()), json.loads(src.read_bytes()))
        dst.write_bytes(json.dumps(merged, separators=(",", ":")).encode())
    else:
        shutil.copyfile(src, dst)
shutil.copyfile(ROOT / "icon.png", PACK / "icon.png")

packwiz("refresh")
fo_metafiles = {p: p.read_bytes() for p in PACK.rglob("*.pw.toml")}
for mod in cfg["mods"]:
    add(mod)
ours = sorted(p for p in PACK.rglob("*.pw.toml") if fo_metafiles.get(p) != p.read_bytes())
listed = {mod.split("/")[0] for mod in cfg["mods"]}
for p in ours:
    slug = p.name.removesuffix(".pw.toml")
    if slug in pins and slug not in listed:
        add(slug)

OUT.parent.mkdir(exist_ok=True)
packwiz("modrinth", "export", "-o", str(OUT))

meta = lambda p: tomllib.loads(p.read_text("utf-8"))
locked = {p.name.removesuffix(".pw.toml"): meta(p)["update"]["modrinth"]["version"] for p in ours}
locked |= {slug: pins[slug] for slug in failed if slug in pins}
mods = "\n".join(f'{json.dumps(slug)} = "{version}"' for slug, version in locked.items())
LOCK.write_text("# Don't edit: generated by modpack/build.py\n"
                f'minecraft = "{minecraft}"\nfo = "{fo_commit}"\nfabric = "{meta(PACK / "pack.toml")["versions"]["fabric"]}"\n\n'
                f"[mods]\n{mods}", "utf-8")

pinned = [mod for mod in cfg["mods"] if "/" in mod]
for label, names in ("mods not added", failed), ("exclude words that matched nothing", unmatched), ("pinned mods", pinned):
    if names:
        print(f"{label}: {', '.join(names)}")